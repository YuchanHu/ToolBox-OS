"""Regenerate the native-size LVGL A8 logo from the design SVG (PyQt5, Pillow)."""
from pathlib import Path
from xml.etree import ElementTree as ET

from PIL import Image
from PyQt5.QtGui import QImage, QPainter
from PyQt5.QtSvg import QSvgRenderer

assets = Path(__file__).resolve().parents[1] / "main/assets"
svg = ET.parse(assets / "toolbox_os_stopwatch_splash_final.svg").getroot()
for element in list(svg):
    if element.get("id") != "logo":
        svg.remove(element)
ET.register_namespace("", "http://www.w3.org/2000/svg")
scale = 4
image = QImage(466 * scale, 466 * scale, QImage.Format_RGBA8888)
image.fill(0)
painter = QPainter(image)
QSvgRenderer(ET.tostring(svg)).render(painter)
painter.end()
rgba = Image.frombytes("RGBA", (image.width(), image.height()), image.bits().asstring(image.byteCount()))
mask = rgba.getchannel("A").resize((466, 466), Image.Resampling.BOX)
x, y, right, bottom = mask.getbbox()
mask = mask.crop((x, y, right, bottom))
pixels = mask.tobytes()
rows = ["    " + ",".join(map(str, pixels[i:i + 32])) + "," for i in range(0, len(pixels), 32)]
source = f"""/* Generated by tools/convert-splash.py. Place at ({x}, {y}) in the 466 px viewport. */
#include <lvgl.h>

static const LV_ATTRIBUTE_MEM_ALIGN uint8_t pixels[] = {{
{chr(10).join(rows)}
}};

const lv_image_dsc_t toolbox_boot_logo = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,
               .w = {mask.width}, .h = {mask.height}, .stride = {mask.width}}},
    .data_size = sizeof(pixels),
    .data = pixels,
}};
"""
(assets / "boot_logo.c").write_text(source, encoding="ascii")
